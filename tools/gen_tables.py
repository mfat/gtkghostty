#!/usr/bin/env python3
"""Generate src/gtk-ghostty-tables.c: GDK key names -> GhosttyKey, and box drawing.

Both tables are ported from tilix2 (https://github.com/markuman/tilix2, tilix2.py
at 65d775b, WTFPL v2): its KEYMAP and its _box_lines()/_blocks() derivation from
Unicode character names. Every GhosttyKey name is checked against the
libghostty-vt headers, so a key the library does not know fails the generation
instead of the build.

    python3 tools/gen_tables.py <path to libghostty-vt include/> > src/gtk-ghostty-tables.c
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

KEYMAP = {
    'Return': 'ENTER', 'KP_Enter': 'NUMPAD_ENTER', 'Escape': 'ESCAPE', 'BackSpace': 'BACKSPACE',
    'Tab': 'TAB', 'ISO_Left_Tab': 'TAB', 'space': 'SPACE',
    'Left': 'ARROW_LEFT', 'Right': 'ARROW_RIGHT', 'Up': 'ARROW_UP', 'Down': 'ARROW_DOWN',
    'Home': 'HOME', 'End': 'END', 'Prior': 'PAGE_UP', 'Page_Up': 'PAGE_UP',
    'Next': 'PAGE_DOWN', 'Page_Down': 'PAGE_DOWN', 'Insert': 'INSERT', 'Delete': 'DELETE',
    'Pause': 'PAUSE', 'Print': 'PRINT_SCREEN', 'Menu': 'CONTEXT_MENU', 'Help': 'HELP',
    'KP_Add': 'NUMPAD_ADD', 'KP_Subtract': 'NUMPAD_SUBTRACT', 'KP_Multiply': 'NUMPAD_MULTIPLY',
    'KP_Divide': 'NUMPAD_DIVIDE', 'KP_Decimal': 'NUMPAD_DECIMAL', 'KP_Separator': 'NUMPAD_SEPARATOR',
    'KP_Equal': 'NUMPAD_EQUAL', 'KP_Left': 'NUMPAD_LEFT', 'KP_Right': 'NUMPAD_RIGHT',
    'KP_Up': 'NUMPAD_UP', 'KP_Down': 'NUMPAD_DOWN', 'KP_Home': 'NUMPAD_HOME', 'KP_End': 'NUMPAD_END',
    'KP_Page_Up': 'NUMPAD_PAGE_UP', 'KP_Page_Down': 'NUMPAD_PAGE_DOWN',
    'KP_Insert': 'NUMPAD_INSERT', 'KP_Delete': 'NUMPAD_DELETE', 'KP_Begin': 'NUMPAD_BEGIN',
    'minus': 'MINUS', 'equal': 'EQUAL', 'comma': 'COMMA', 'period': 'PERIOD', 'slash': 'SLASH',
    'semicolon': 'SEMICOLON', 'apostrophe': 'QUOTE', 'grave': 'BACKQUOTE', 'backslash': 'BACKSLASH',
    'bracketleft': 'BRACKET_LEFT', 'bracketright': 'BRACKET_RIGHT',
}
for _c in '0123456789':
    KEYMAP[_c] = f'DIGIT_{_c}'
for _c in 'abcdefghijklmnopqrstuvwxyz':
    KEYMAP[_c] = KEYMAP[_c.upper()] = _c.upper()
for _i in range(1, 36):
    KEYMAP[f'F{_i}'] = f'F{_i}'
for _i in range(10):
    KEYMAP[f'KP_{_i}'] = f'NUMPAD_{_i}'


def box_lines():
    """U+2500-257F -> ((left, right, up, down) weights 0/1/2, rounded). Dashes,
    diagonals and double lines stay with the font (as in tilix2)."""
    weights = {'LIGHT': 1, 'SINGLE': 1, 'HEAVY': 2}
    dirs = {'LEFT': (0,), 'RIGHT': (1,), 'UP': (2,), 'DOWN': (3,), 'HORIZONTAL': (0, 1), 'VERTICAL': (2, 3)}
    out = {}
    for cp in range(0x2500, 0x2580):
        name = unicodedata.name(chr(cp), '').removeprefix('BOX DRAWINGS ')
        if any(s in name for s in ('DASH', 'DIAGONAL', 'DOUBLE')):
            continue
        default = weights.get(name.split()[0], 1)
        arms = [0, 0, 0, 0]
        for part in name.split(' AND '):
            weight = next((weights[s] for s in part.split() if s in weights), default)
            for s in part.split():
                for i in dirs.get(s, ()):
                    arms[i] = weight
        out[cp] = (tuple(arms), 'ARC' in name)
    return out


def blocks():
    """U+2580-259F -> rects (x, y, w, h) as fractions of the cell."""
    b = {'▀': [(0, 0, 1, .5)], '▐': [(.5, 0, .5, 1)], '▔': [(0, 0, 1, 1 / 8)], '▕': [(7 / 8, 0, 1 / 8, 1)]}
    for i, c in enumerate('▁▂▃▄▅▆▇█', 1):
        b[c] = [(0, 1 - i / 8, 1, i / 8)]
    for i, c in enumerate('▏▎▍▌▋▊▉', 1):
        b[c] = [(0, 0, i / 8, 1)]
    q = {'UL': (0, 0, .5, .5), 'UR': (.5, 0, .5, .5), 'LL': (0, .5, .5, .5), 'LR': (.5, .5, .5, .5)}
    for c, parts in (('▘', 'UL'), ('▝', 'UR'), ('▖', 'LL'), ('▗', 'LR'), ('▚', 'UL LR'), ('▞', 'UR LL'),
                     ('▙', 'UL LL LR'), ('▛', 'UL UR LL'), ('▜', 'UL UR LR'), ('▟', 'UR LL LR')):
        b[c] = [q[p] for p in parts.split()]
    return {ord(c): rects for c, rects in b.items()}


SHADES = {0x2591: .25, 0x2592: .5, 0x2593: .75}


def main(include: Path) -> None:
    header = (include / "ghostty" / "vt" / "key" / "event.h").read_text(encoding="utf-8")
    known = set(re.findall(r"\bGHOSTTY_KEY_([A-Z0-9_]+)\s*=", header))
    # tilix2 maps F1-F35 (pyghostty's pre-1.0 build); keep the F keys this release has.
    for name in [n for n, key in KEYMAP.items() if re.fullmatch(r"F\d+", key) and key not in known]:
        del KEYMAP[name]
    missing = sorted({v for v in KEYMAP.values() if v not in known})
    if missing:
        sys.exit(f"GhosttyKey names not in this libghostty-vt: {missing}")

    out = [
        "/* Generated by tools/gen_tables.py -- do not edit.",
        " * Key map and box-drawing tables ported from tilix2 (WTFPL v2),",
        " * https://github.com/markuman/tilix2 at 65d775b. */",
        "",
        '#include "gtk-ghostty-tables.h"',
        "",
        "#include <string.h>",
        "",
        "static const struct { const char *name; GhosttyKey key; } keymap[] = {",
    ]
    for name in sorted(KEYMAP):
        out.append(f'  {{ "{name}", GHOSTTY_KEY_{KEYMAP[name]} }},')
    out += [
        "};",
        "",
        "GhosttyKey",
        "gtk_ghostty_key_from_name (const char *name)",
        "{",
        "  size_t lo = 0, hi = G_N_ELEMENTS (keymap);",
        "  if (name == NULL)",
        "    return GHOSTTY_KEY_UNIDENTIFIED;",
        "  while (lo < hi)",
        "    {",
        "      size_t mid = (lo + hi) / 2;",
        "      int cmp = strcmp (name, keymap[mid].name);",
        "      if (cmp == 0)",
        "        return keymap[mid].key;",
        "      if (cmp < 0)",
        "        hi = mid;",
        "      else",
        "        lo = mid + 1;",
        "    }",
        "  return GHOSTTY_KEY_UNIDENTIFIED;",
        "}",
        "",
    ]
    lines, rects = box_lines(), blocks()
    out.append("static const GtkGhosttyBoxGlyph box_lines[0x80] = {")
    for cp in range(0x2500, 0x2580):
        if cp in lines:
            arms, arc = lines[cp]
            out.append(f"  [0x{cp - 0x2500:02x}] = {{ GTK_GHOSTTY_BOX_LINES, {{ {', '.join(map(str, arms))} }}, {int(arc)}, 0, {{ {{ 0 }} }}, 0 }},")
    out.append("};")
    out.append("")
    out.append("static const GtkGhosttyBoxGlyph box_blocks[0x20] = {")
    for cp in range(0x2580, 0x25A0):
        if cp in rects:
            items = ", ".join("{ %.6ff, %.6ff, %.6ff, %.6ff }" % r for r in rects[cp])
            out.append(f"  [0x{cp - 0x2580:02x}] = {{ GTK_GHOSTTY_BOX_RECTS, {{ 0 }}, 0, {len(rects[cp])}, {{ {items} }}, 0 }},")
        elif cp in SHADES:
            out.append(f"  [0x{cp - 0x2580:02x}] = {{ GTK_GHOSTTY_BOX_SHADE, {{ 0 }}, 0, 0, {{ {{ 0 }} }}, {SHADES[cp]:.2f}f }},")
    out += [
        "};",
        "",
        "const GtkGhosttyBoxGlyph *",
        "gtk_ghostty_box_glyph (gunichar c)",
        "{",
        "  const GtkGhosttyBoxGlyph *glyph = NULL;",
        "  if (c >= 0x2500 && c < 0x2580)",
        "    glyph = &box_lines[c - 0x2500];",
        "  else if (c >= 0x2580 && c < 0x25A0)",
        "    glyph = &box_blocks[c - 0x2580];",
        "  return glyph != NULL && glyph->kind != GTK_GHOSTTY_BOX_NONE ? glyph : NULL;",
        "}",
        "",
    ]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
